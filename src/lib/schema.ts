// Esquema de PostgreSQL. Sin dependencias para que lo use también el script de migración.
// Los "booleanos" se guardan como INTEGER 0/1 para mantener el mismo formato que la app ya usa.

export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS restaurants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  tagline TEXT NOT NULL DEFAULT '',
  logo_url TEXT NOT NULL DEFAULT '',
  google_review_url TEXT NOT NULL DEFAULT '',
  menu_file TEXT,
  settings TEXT NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS tables (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  number INTEGER NOT NULL,
  area TEXT NOT NULL DEFAULT '',
  token TEXT UNIQUE NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (restaurant_id, number)
);

CREATE TABLE IF NOT EXISTS table_sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  table_id INTEGER NOT NULL REFERENCES tables(id),
  status TEXT NOT NULL CHECK (status IN ('pending','open','closed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  opened_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ,
  reward_used INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_sessions_table ON table_sessions(table_id, status);
-- Una mesa no puede tener dos sesiones vivas a la vez (p. ej. dos celulares escaneando al mismo tiempo).
CREATE UNIQUE INDEX IF NOT EXISTS uniq_live_session ON table_sessions(table_id) WHERE status IN ('pending','open');

CREATE TABLE IF NOT EXISTS staff (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  username TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('owner','staff')),
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS board_games (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  name TEXT NOT NULL,
  genre TEXT NOT NULL DEFAULT '',
  min_players INTEGER NOT NULL DEFAULT 2,
  max_players INTEGER NOT NULL DEFAULT 4,
  minutes INTEGER NOT NULL DEFAULT 30,
  summary TEXT NOT NULL DEFAULT '',
  cover_file TEXT,
  back_file TEXT,
  available INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS prizes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  name TEXT NOT NULL,
  weight INTEGER NOT NULL DEFAULT 1,
  stock INTEGER,
  active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS reward_plays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  session_id INTEGER NOT NULL REFERENCES table_sessions(id),
  table_id INTEGER NOT NULL REFERENCES tables(id),
  game TEXT NOT NULL CHECK (game IN ('ruleta','rasca','gato')),
  status TEXT NOT NULL CHECK (status IN ('playing','won','lost')),
  state TEXT,
  prize_id INTEGER,
  prize_name TEXT,
  code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_plays_session ON reward_plays(session_id);

CREATE TABLE IF NOT EXISTS requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  table_id INTEGER NOT NULL REFERENCES tables(id),
  session_id INTEGER NOT NULL REFERENCES table_sessions(id),
  type TEXT NOT NULL CHECK (type IN ('waiter','boardgame','prize')),
  message TEXT,
  board_game_id INTEGER,
  reward_play_id INTEGER,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','attending','done','cancelled')),
  handled_by INTEGER,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_requests_rest ON requests(restaurant_id, status);
CREATE INDEX IF NOT EXISTS idx_requests_session ON requests(session_id);

-- Archivos subidos (menú PDF, portadas): viven en la base para no depender del disco de un servidor.
CREATE TABLE IF NOT EXISTS files (
  name TEXT PRIMARY KEY,
  restaurant_id INTEGER REFERENCES restaurants(id),
  mime TEXT NOT NULL,
  size INTEGER NOT NULL,
  data BYTEA NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Valores compartidos por todos los servidores (p. ej. la clave para firmar cookies).
CREATE TABLE IF NOT EXISTS app_secrets (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- ---------- Estadísticas ----------
-- Zona horaria del negocio: los días y horas pico se cuentan con su reloj, no el del servidor.
ALTER TABLE restaurants ADD COLUMN IF NOT EXISTS timezone TEXT NOT NULL DEFAULT 'America/Tijuana';
-- Primera vez que el personal atendió la solicitud ("voy" o "listo"): mide el tiempo de respuesta.
ALTER TABLE requests ADD COLUMN IF NOT EXISTS responded_at TIMESTAMPTZ;

-- Eventos del cliente que no generan solicitud (ver el menú, abrir el enlace de reseña…).
CREATE TABLE IF NOT EXISTS analytics_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL REFERENCES restaurants(id),
  session_id INTEGER REFERENCES table_sessions(id),
  table_id INTEGER REFERENCES tables(id),
  type TEXT NOT NULL CHECK (type IN ('menu_view','review_click','ludoteca_view')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_events_rest ON analytics_events(restaurant_id, type, created_at);
CREATE INDEX IF NOT EXISTS idx_sessions_opened ON table_sessions(restaurant_id, opened_at);
CREATE INDEX IF NOT EXISTS idx_requests_created ON requests(restaurant_id, created_at);
`;

/** Tablas con columna id autoincremental, en orden de dependencias (para migrar y reiniciar contadores). */
export const ID_TABLES = [
  "restaurants",
  "tables",
  "staff",
  "table_sessions",
  "board_games",
  "prizes",
  "reward_plays",
  "requests",
] as const;

